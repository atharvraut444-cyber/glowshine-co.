/**
 * Helper to compute GlowMatch score for a product based on user beauty profile
 */
export function calculateProductMatch(product, beautyProfile) {
  if (!beautyProfile) return Math.floor(Math.random() * 15) + 80; // default 80-95%

  let score = 70; // baseline
  const { skinType, primaryConcern, concerns = [] } = beautyProfile;

  // Skin type match (+15)
  if (product.skinTypes.includes('all') || (skinType && product.skinTypes.includes(skinType))) {
    score += 15;
  }

  // Primary concern match (+10)
  if (primaryConcern && product.concerns.includes(primaryConcern)) {
    score += 10;
  }

  // Secondary concerns (+5)
  const matchingConcerns = concerns.filter((c) => product.concerns.includes(c));
  score += Math.min(5, matchingConcerns.length * 3);

  // Cap score between 75% and 98%
  return Math.min(98, Math.max(75, score));
}
